def series(start, end, n=13, wobble=0.35, nd=1, seed=1):
    """Ряд из n точек от start к end с небольшим дрожанием; концы точные."""
    r = random.Random(seed)
    out = []
    for i in range(n):
        t = i / (n - 1)
        v = start + (end - start) * t + (r.uniform(-wobble, wobble) if 0 < i < n - 1 else 0)
        out.append(round(v, nd))
    out[0], out[-1] = start, end
    return out


